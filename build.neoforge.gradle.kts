	mavenCentral()
	strictMaven("https://api.modrinth.com/maven", "maven.modrinth") { name = "Modrinth" }
	strictMaven("https://dl.cloudsmith.io/public/geckolib3/geckolib/maven/", "software.bernie.geckolib") { name = "GeckoLib" }
}

